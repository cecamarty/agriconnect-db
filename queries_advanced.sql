USE agriconnect;

-- Drop views if they exist to allow clean creation
DROP VIEW IF EXISTS v_order_fulfillment;
DROP VIEW IF EXISTS v_monthly_financial_summary;
DROP VIEW IF EXISTS v_catalog;
DROP VIEW IF EXISTS v_farmer_earnings;

-- ------------------------------------------------------------------------------
-- 1. Top 3 Products per Category (Window Partition Ranking)
-- Uses Common Table Expressions (CTEs) and ROW_NUMBER() / DENSE_RANK()
-- ------------------------------------------------------------------------------
WITH prod_sales AS (
    SELECT 
        p.category, 
        p.product_id,
        p.product_name, 
        COALESCE(SUM(oi.qty), 0) AS total_qty_sold,
        COALESCE(SUM(oi.line_total), 0) AS total_revenue
    FROM products p
    JOIN order_items oi ON p.product_id = oi.product_id
    JOIN orders o ON oi.order_id = o.order_id
    WHERE o.status = 'DELIVERED'
    GROUP BY p.category, p.product_id, p.product_name
),
ranked_products AS (
    SELECT 
        category,
        product_id,
        product_name,
        total_qty_sold,
        total_revenue,
        ROW_NUMBER() OVER (
            PARTITION BY category 
            ORDER BY total_qty_sold DESC, total_revenue DESC
        ) AS rnk
    FROM prod_sales
)
SELECT 
    category, 
    rnk AS category_rank,
    product_name, 
    total_qty_sold,
    total_revenue
FROM ranked_products 
WHERE rnk <= 3
ORDER BY category, rnk;

-- ------------------------------------------------------------------------------
-- 2. Month-over-Month Platform Revenue & Growth Rate using LAG()
-- Analyzes delivered revenue trends, monetary variance, and MoM growth %
-- ------------------------------------------------------------------------------
WITH monthly_revenue AS (
    SELECT 
        DATE_FORMAT(order_date, '%Y-%m') AS yr_mo, 
        COUNT(order_id) AS orders_count,
        SUM(total_amount) AS rev,
        ROUND(SUM(total_amount) * 0.05, 2) AS commission_earned
    FROM orders 
    WHERE status = 'DELIVERED'
    GROUP BY DATE_FORMAT(order_date, '%Y-%m')
)
SELECT 
    yr_mo, 
    orders_count,
    rev AS monthly_gross_gmv,
    commission_earned AS platform_5pct_take,
    rev - LAG(rev) OVER (ORDER BY yr_mo) AS diff_from_prev_month,
    ROUND(
        100.0 * (rev - LAG(rev) OVER (ORDER BY yr_mo)) 
        / NULLIF(LAG(rev) OVER (ORDER BY yr_mo), 0), 
        1
    ) AS pct_mom_growth
FROM monthly_revenue
ORDER BY yr_mo;

-- ------------------------------------------------------------------------------
-- 3. Farmer Earnings Leaderboard with RANK() & DENSE_RANK()
-- Computes net payout after 5% platform commission
-- ------------------------------------------------------------------------------
SELECT 
    u.user_id AS farmer_id,
    u.full_name,
    t.town_name,
    SUM(oi.line_total) AS gross_sales,
    ROUND(SUM(oi.line_total) * 0.05, 2) AS platform_deduction,
    ROUND(SUM(oi.line_total) * 0.95, 2) AS net_earnings,
    RANK() OVER (ORDER BY SUM(oi.line_total) DESC) AS sales_rank,
    DENSE_RANK() OVER (ORDER BY SUM(oi.line_total) DESC) AS dense_sales_rank
FROM order_items oi
JOIN products p ON p.product_id = oi.product_id
JOIN users u ON u.user_id = p.farmer_id
JOIN towns t ON u.town_id = t.town_id
JOIN orders o ON oi.order_id = o.order_id
WHERE o.status = 'DELIVERED'
GROUP BY u.user_id, u.full_name, t.town_name
ORDER BY sales_rank ASC;

-- ------------------------------------------------------------------------------
-- 4. Cumulative Running Total & Moving Average of Delivered Revenue
-- Evaluates cash flow velocity using unbounded and sliding frame windows
-- ------------------------------------------------------------------------------
SELECT 
    order_id,
    order_date,
    total_amount,
    SUM(total_amount) OVER (
        ORDER BY order_date, order_id 
        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
    ) AS cumulative_running_gmv,
    ROUND(AVG(total_amount) OVER (
        ORDER BY order_date, order_id 
        ROWS BETWEEN 2 PRECEDING AND CURRENT ROW
    ), 2) AS moving_avg_3_orders
FROM orders
WHERE status = 'DELIVERED'
ORDER BY order_date, order_id;

-- ------------------------------------------------------------------------------
-- 5. Category Contribution to Total Revenue using Window SUM() OVER ()
-- Determines the percentage of total sales generated by each product category
-- ------------------------------------------------------------------------------
SELECT 
    p.category,
    SUM(oi.line_total) AS category_revenue,
    SUM(SUM(oi.line_total)) OVER () AS total_platform_revenue,
    ROUND(
        100.0 * SUM(oi.line_total) / SUM(SUM(oi.line_total)) OVER (), 
        2
    ) AS pct_contribution_to_total
FROM products p
JOIN order_items oi ON p.product_id = oi.product_id
JOIN orders o ON oi.order_id = o.order_id
WHERE o.status = 'DELIVERED'
GROUP BY p.category
ORDER BY category_revenue DESC;

-- ------------------------------------------------------------------------------
-- 6. Reusable View 1: v_farmer_earnings
-- Admin dashboard view tracking gross GMV and net farmer balance payout
-- ------------------------------------------------------------------------------
CREATE VIEW v_farmer_earnings AS
SELECT 
    p.farmer_id, 
    u.full_name,
    u.phone,
    COUNT(DISTINCT o.order_id) AS total_orders_served,
    COALESCE(SUM(oi.line_total), 0.00) AS gross_sales,
    ROUND(COALESCE(SUM(oi.line_total), 0.00) * 0.05, 2) AS platform_commission,
    ROUND(COALESCE(SUM(oi.line_total), 0.00) * 0.95, 2) AS net_earnings
FROM products p
JOIN users u ON u.user_id = p.farmer_id
LEFT JOIN order_items oi ON p.product_id = oi.product_id
LEFT JOIN orders o ON oi.order_id = o.order_id AND o.status = 'DELIVERED'
GROUP BY p.farmer_id, u.full_name, u.phone;

-- ------------------------------------------------------------------------------
-- 7. Reusable View 2: v_catalog
-- Public customer-facing product catalog with real-time stock availability
-- ------------------------------------------------------------------------------
CREATE VIEW v_catalog AS
SELECT 
    p.product_id, 
    p.product_name, 
    p.category, 
    p.unit, 
    p.unit_price,
    p.stock_qty,
    (p.stock_qty > 0) AS in_stock,
    u.user_id AS farmer_id,
    u.full_name AS farmer_name,
    t.town_name AS farm_location
FROM products p
JOIN users u ON p.farmer_id = u.user_id
JOIN towns t ON u.town_id = t.town_id
WHERE p.is_active = TRUE;

-- ------------------------------------------------------------------------------
-- 8. Reusable View 3: v_monthly_financial_summary
-- Executive KPI view aggregating GMV, platform fees, and orders by month
-- ------------------------------------------------------------------------------
CREATE VIEW v_monthly_financial_summary AS
SELECT 
    DATE_FORMAT(order_date, '%Y-%m') AS billing_month,
    COUNT(order_id) AS total_orders,
    SUM(CASE WHEN status = 'DELIVERED' THEN 1 ELSE 0 END) AS delivered_orders,
    SUM(CASE WHEN status = 'CANCELLED' THEN 1 ELSE 0 END) AS cancelled_orders,
    COALESCE(SUM(CASE WHEN status = 'DELIVERED' THEN total_amount ELSE 0 END), 0.00) AS gross_delivered_gmv,
    ROUND(COALESCE(SUM(CASE WHEN status = 'DELIVERED' THEN total_amount ELSE 0 END), 0.00) * 0.05, 2) AS net_platform_commission
FROM orders
GROUP BY DATE_FORMAT(order_date, '%Y-%m');

-- ------------------------------------------------------------------------------
-- 9. Reusable View 4: v_order_fulfillment
-- Logistics monitoring view tracking dispatch delays and driver performance
-- ------------------------------------------------------------------------------
CREATE VIEW v_order_fulfillment AS
SELECT 
    o.order_id,
    o.order_date,
    o.status AS order_status,
    u.full_name AS buyer_name,
    u.phone AS buyer_phone,
    o.delivery_address,
    d.driver_name,
    d.driver_phone,
    d.status AS delivery_status,
    d.dispatched_at,
    d.delivered_at,
    TIMESTAMPDIFF(MINUTE, d.dispatched_at, d.delivered_at) AS delivery_duration_minutes
FROM orders o
LEFT JOIN deliveries d ON o.order_id = d.order_id
JOIN users u ON o.buyer_id = u.user_id;
